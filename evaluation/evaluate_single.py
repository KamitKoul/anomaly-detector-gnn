def evaluate_experiment(exp_dir: Path, eval_limit_override: Optional[int] = None) -> int:
    """Executes single experiment evaluation or reports missing prerequisites."""
    config_path = exp_dir / "config.json"
    checkpoint_path = exp_dir / "checkpoint.pt"

    if not config_path.exists():
        print(f"[ERROR] config.json not found in {exp_dir}")
        return 1

    config = load_config(config_path)
    print(f"Loaded experiment: {config.experiment_name} ({config.experiment_family})")

    # Check checkpoint existence
    if not checkpoint_path.exists():
        print(f"[STATUS] Checkpoint '{checkpoint_path}' does not exist.")
        print("         Experiment has not been trained yet. Evaluation cannot proceed.")
        return 0

    # Check dataset availability
    ds = check_dataset_availability(config, repo_root=REPO_ROOT)
    if not ds["background_available"] or not ds["signal_available"]:
        print("[STATUS] Datasets are not available locally:")
        print(f"         Background available: {ds['background_available']} ({ds['background_path']})")
        print(f"         Signal available:     {ds['signal_available']} ({ds['signal_path']})")
        print("         Evaluation cannot proceed without datasets.")
        return 0

    print("[INFO] Checkpoint and datasets verified. Proceeding with evaluation...")

    import numpy as np
    import torch
    import torch.nn.functional as F
    from src.run_lhco_gnn import (
        create_model,
        event_to_graph,
        event_to_flat_features,
        chunk_to_flat_features,
        stream_filtered_events,
        get_device,
    )
    from src.adversarial_unlearning_ae import AdversarialNodeGNN

    device = get_device()
    model = create_model(config).to(device)
    model.load_state_dict(torch.load(checkpoint_path, map_location=device))
    model.eval()

    eval_limit = eval_limit_override if eval_limit_override is not None else config.dataset.eval_limit
    if eval_limit_override is not None:
        if eval_limit_override <= 0:
            eval_limit = None
            print("[OVERRIDE] Full dataset evaluation enabled: streaming ALL events to EOF.")
        else:
            print(f"[OVERRIDE] Using custom eval_limit: {eval_limit} events (config default: {config.dataset.eval_limit})")
    arch_type = config.model.architecture_type

    def score_event_population(
        file_path: Path,
        is_signal: bool,
        train_skip: int = 0,
        batch_size: int = 128,
    ) -> List[float]:
        """
        Saturates GPU utilization by batching event inference and executing per-graph loss reduction on device.
        - For baseline_mlp: processes full HDF5 chunks in parallel via vectorized 2D matrix multiplications.
        - For GNN models: batches 128 graphs into disjoint block-diagonal tensors, computing MSE on GPU with scatter_add_.
        """
        scores: List[float] = []
        skipped = 0
        count = 0
        pop_name = "signal" if is_signal else "background"

        if arch_type == "baseline_mlp":
            chunk_size = 2000
            for chunk in stream_filtered_events(str(file_path), is_signal=is_signal, chunk_size=chunk_size):
                chunk_len = len(chunk)
                if chunk_len == 0:
                    continue

                start_idx = 0
                if skipped < train_skip:
                    needed = train_skip - skipped
                    if chunk_len <= needed:
                        skipped += chunk_len
                        continue
                    else:
                        start_idx = needed
                        skipped = train_skip

                available = chunk_len - start_idx
                if eval_limit is not None:
                    remaining = eval_limit - count
                    if remaining <= 0:
                        break
                    take_len = min(available, remaining)
                else:
                    take_len = available

                chunk_slice = chunk[start_idx : start_idx + take_len]
                batch_x = chunk_to_flat_features(
                    chunk_slice,
                    input_dim=config.model.input_dim,
                    log_pt=config.graph_construction.log_pt,
                ).to(device, non_blocking=True)

                with torch.no_grad():
                    recon_x = model(batch_x)
                    batch_scores = F.mse_loss(recon_x, batch_x, reduction="none").mean(dim=1)

                scores.extend(batch_scores.cpu().tolist())
                count += take_len
                if count % 50000 < take_len or (count >= 10000 and count % 10000 == 0):
                    print(f"  [PROGRESS] Evaluated {count} {pop_name} events on GPU...")
                if eval_limit is not None and count >= eval_limit:
                    break
        else:
            delta_r = config.graph_construction.delta_r_threshold
            log_pt = config.graph_construction.log_pt
            include_met = config.graph_construction.include_met_node
            phi_mode = config.graph_construction.phi_met_mode
            graph_buffer: List[Any] = []

            def flush_graph_buffer():
                nonlocal graph_buffer, scores
                if not graph_buffer:
                    return
                from torch_geometric.data import Batch
                batched_graph = Batch.from_data_list(graph_buffer).to(device, non_blocking=True)
                with torch.no_grad():
                    if isinstance(model, AdversarialNodeGNN):
                        recon_x, _, _ = model(batched_graph.x, batched_graph.edge_index, batched_graph.batch)
                    else:
                        recon_x, _ = model(batched_graph.x, batched_graph.edge_index, batched_graph.batch)

                    node_err = (recon_x - batched_graph.x).pow(2).mean(dim=1)
                    num_g = batched_graph.num_graphs
                    graph_err_sums = torch.zeros(num_g, device=device).scatter_add_(0, batched_graph.batch, node_err)
                    graph_node_counts = torch.zeros(num_g, device=device).scatter_add_(0, batched_graph.batch, torch.ones_like(node_err))
                    batch_scores = (graph_err_sums / graph_node_counts.clamp(min=1.0)).cpu().tolist()

                scores.extend(batch_scores)
                graph_buffer.clear()

            for chunk in stream_filtered_events(str(file_path), is_signal=is_signal, chunk_size=1000):
                for i in range(len(chunk)):
                    if skipped < train_skip:
                        skipped += 1
                        continue
                    if eval_limit is not None and count >= eval_limit:
                        break

                    event = chunk[i]
                    graph = event_to_graph(
                        event,
                        log_pt=log_pt,
                        delta_r_threshold=delta_r,
                        include_met_node=include_met,
                        phi_met_mode=phi_mode,
                    )
                    graph_buffer.append(graph)
                    count += 1

                    if len(graph_buffer) >= batch_size:
                        flush_graph_buffer()
                        if count % 50000 < batch_size or (count >= 10000 and count % 10000 == 0):
                            print(f"  [PROGRESS] Evaluated {count} {pop_name} events on GPU...")
                if eval_limit is not None and count >= eval_limit:
                    break

            flush_graph_buffer()

        return scores

    # Score background events (skip train_limit to avoid evaluation leakage)
    train_skip = getattr(config.dataset, "train_limit", 0)
    bg_limit_desc = f"{eval_limit} unseen" if eval_limit else f"ALL available (skipping {train_skip} training events)"
    print(f"[INFO] Scoring {bg_limit_desc} background events (GPU accelerated)...")
    bg_path = REPO_ROOT / config.dataset.background_path
    bg_scores = score_event_population(bg_path, is_signal=False, train_skip=train_skip, batch_size=128)

    # Score signal events (truth == 1)
    sig_limit_desc = f"{eval_limit}" if eval_limit else "ALL available genuine"
    print(f"[INFO] Scoring {sig_limit_desc} signal events (GPU accelerated)...")
    sig_path = REPO_ROOT / config.dataset.signal_path
    sig_scores = score_event_population(sig_path, is_signal=True, train_skip=0, batch_size=128)

    # Labels: 0 for background, 1 for signal
    labels = [0] * len(bg_scores) + [1] * len(sig_scores)
    all_scores = bg_scores + sig_scores

    roc_metrics = compute_roc_metrics(labels, all_scores)
    sep_metrics = compute_separation_statistics(bg_scores, sig_scores)

    combined_metrics = {
        "experiment_name": config.experiment_name,
        "experiment_family": config.experiment_family,
        "eval_limit_bg": len(bg_scores),
        "eval_limit_sig": len(sig_scores),
        **roc_metrics,
        **sep_metrics,
    }

    # Save metrics.json
    metrics_path = exp_dir / "metrics.json"
    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump(combined_metrics, f, indent=2)
    print(f"[INFO] Metrics written: {metrics_path}")

    # Save predictions.npz
    preds_path = exp_dir / "predictions.npz"
    np.savez_compressed(
        preds_path,
        bg_scores=np.array(bg_scores, dtype=np.float32),
        sig_scores=np.array(sig_scores, dtype=np.float32),
        labels=np.array(labels, dtype=np.int32),
        scores=np.array(all_scores, dtype=np.float32),
    )
    print(f"[INFO] Predictions written: {preds_path}")

    print(f"[RESULT] ROC AUC: {roc_metrics['roc_auc']:.4f} | Separation ratio: {sep_metrics['separation_ratio']:.4f}")
    return 0


def main():
    parser = argparse.ArgumentParser(description="Evaluate a single experiment directory")
    parser.add_argument(
        "--experiment",
        type=str,
        required=True,
        help="Path to experiment directory (e.g., experiments/architecture/gat_met_production)",
    )
    parser.add_argument(
        "--eval-limit",
        type=int,
        default=None,
        help="Override the evaluation population event count (default: config.dataset.eval_limit)",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="Evaluate on ALL available events (all ~1M background + all 100k signal events)",
    )
    args = parser.parse_args()

    exp_dir = Path(args.experiment)
    if not exp_dir.exists():
        print(f"[ERROR] Directory does not exist: {exp_dir}")
        sys.exit(1)

    override = -1 if args.all else args.eval_limit
    sys.exit(evaluate_experiment(exp_dir, eval_limit_override=override))


if __name__ == "__main__":
    main()
