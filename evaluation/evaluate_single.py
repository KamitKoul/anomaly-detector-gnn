"""
evaluate_single.py — Single Experiment Evaluation Scaffold
===========================================================
Evaluates a single completed experiment directory adhering to the output contract:
  experiments/<family>/<experiment_name>/
  ├── config.json
  ├── checkpoint.pt
  ├── predictions.npz  (generated by this script)
  ├── metrics.json     (generated by this script)
  └── plots/

Usage:
  python evaluation/evaluate_single.py --experiment experiments/architecture/gat_met_production

Scaffolding Design:
  - Reuses exact evaluation metrics from src/ultimate_discovery_proof.py and src/run_lhco_gnn.py.
  - Gracefully checks dataset and checkpoint availability; never fabricates dummy results.
"""

from __future__ import annotations

import os
import sys
import json
import argparse
from pathlib import Path
from typing import Dict, Any, Tuple

# Add repository root to path
REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from src.experiment_framework import load_config, check_dataset_availability


def compute_roc_metrics(labels, scores) -> Dict[str, float]:
    """Computes ROC AUC and background rejection at standard HEP operating points."""
    import numpy as np
    from sklearn.metrics import roc_curve, roc_auc_score

    labels_arr = np.array(labels)
    scores_arr = np.array(scores)

    auc = float(roc_auc_score(labels_arr, scores_arr))
    fpr, tpr, thresholds = roc_curve(labels_arr, scores_arr)

    # Calculate background rejection (1 / FPR) at 30% and 50% signal efficiency
    rejection_30 = float("inf")
    rejection_50 = float("inf")

    idx_30 = np.where(tpr >= 0.30)[0]
    if len(idx_30) > 0 and fpr[idx_30[0]] > 0:
        rejection_30 = float(1.0 / fpr[idx_30[0]])

    idx_50 = np.where(tpr >= 0.50)[0]
    if len(idx_50) > 0 and fpr[idx_50[0]] > 0:
        rejection_50 = float(1.0 / fpr[idx_50[0]])

    return {
        "roc_auc": round(auc, 4),
        "background_rejection_at_30_eff": round(rejection_30, 2) if rejection_30 != float("inf") else -1.0,
        "background_rejection_at_50_eff": round(rejection_50, 2) if rejection_50 != float("inf") else -1.0,
    }


def compute_separation_statistics(bg_scores, sig_scores) -> Dict[str, float]:
    """Reuses exact statistical separation formulation from src/ultimate_discovery_proof.py."""
    import numpy as np

    bg_arr = np.array(bg_scores)
    sig_arr = np.array(sig_scores)

    mu_bg = float(np.mean(bg_arr)) if len(bg_arr) > 0 else 0.0
    sigma_bg = float(np.std(bg_arr)) if len(bg_arr) > 0 else 1e-8
    mu_sig = float(np.mean(sig_arr)) if len(sig_arr) > 0 else 0.0

    ratio = (mu_sig / mu_bg) if mu_bg > 0 else 0.0
    significance = (mu_sig - mu_bg) / (sigma_bg if sigma_bg > 0 else 1e-8)

    return {
        "separation_ratio": round(ratio, 4),
        "significance_sigma": round(significance, 2),
        "bg_mean_score": round(mu_bg, 6),
        "sig_mean_score": round(mu_sig, 6),
        "bg_std_score": round(sigma_bg, 6),
    }


